#!/usr/bin/env python3

"""
Live ML Inference V1

Runs the legacy DDoS Random Forest model against feature windows
generated by live_feature_adapter_v1.py.

This component performs inference only.
It does not block, rate-limit, isolate, or modify network traffic.
"""

import csv
from pathlib import Path

import joblib
import pandas as pd


MODEL_PATH = Path("detection/ddos_model.pkl")
INPUT_FILE = Path("dataset/live_features_v1.csv")
OUTPUT_FILE = Path("dataset/live_predictions_v1.csv")


FEATURES = [
    "packet_count",
    "bytes_total",
    "packets_per_second",
    "bytes_per_second",
    "unique_sources",
    "unique_destinations",
    "udp_count",
    "tcp_count",
    "icmp_count",
    "syn_count",
    "ack_count",
    "rst_count",
    "fin_count",
    "average_packet_size",
    "flow_count",
]


def validate_model(model):
    expected_classes = {"DDOS_UDP", "NORMAL"}

    if getattr(model, "n_features_in_", None) != len(FEATURES):
        raise ValueError(
            f"Model expects {getattr(model, 'n_features_in_', None)} "
            f"features, expected {len(FEATURES)}"
        )

    actual_classes = set(model.classes_)

    if actual_classes != expected_classes:
        raise ValueError(
            f"Unexpected model classes: {sorted(actual_classes)}"
        )


def main():
    print("=" * 60)
    print("LIVE ML INFERENCE V1")
    print("=" * 60)

    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Model not found: {MODEL_PATH}"
        )

    if not INPUT_FILE.exists():
        raise FileNotFoundError(
            f"Feature input not found: {INPUT_FILE}"
        )

    print("\n[1] Loading model:")
    model = joblib.load(MODEL_PATH)
    validate_model(model)

    print("Model:", type(model).__name__)
    print("Features:", model.n_features_in_)
    print("Classes:", list(model.classes_))

    print("\n[2] Loading feature windows:")
    df = pd.read_csv(INPUT_FILE)

    expected_columns = [
        "window_start",
        *FEATURES,
    ]

    if list(df.columns) != expected_columns:
        raise ValueError(
            "Input schema does not exactly match expected schema.\n"
            f"Expected: {expected_columns}\n"
            f"Actual:   {list(df.columns)}"
        )

    print("Windows:", len(df))

    if df.empty:
        raise ValueError("Feature input contains no windows.")

    print("\n[3] Validating feature values:")

    for feature in FEATURES:
        df[feature] = pd.to_numeric(
            df[feature],
            errors="raise",
        )

    if df[FEATURES].isnull().any().any():
        raise ValueError(
            "Feature input contains missing values."
        )

    print("All 15 features numeric: True")
    print("Missing values: 0")

    print("\n[4] Running inference:")

    predictions = model.predict(df[FEATURES])
    probabilities = model.predict_proba(df[FEATURES])

    class_to_index = {
        cls: i
        for i, cls in enumerate(model.classes_)
    }

    ddos_index = class_to_index["DDOS_UDP"]
    normal_index = class_to_index["NORMAL"]

    df["prediction"] = predictions
    df["ddos_probability"] = probabilities[:, ddos_index]
    df["normal_probability"] = probabilities[:, normal_index]

    output_columns = [
        "window_start",
        *FEATURES,
        "prediction",
        "ddos_probability",
        "normal_probability",
    ]

    df[output_columns].to_csv(
        OUTPUT_FILE,
        index=False,
        float_format="%.6f",
    )

    print("Inference completed.")

    print("\n[5] Prediction distribution:")
    print(df["prediction"].value_counts().to_string())

    print("\n[6] Inference results:")
    for _, row in df.iterrows():
        print(
            f"{row['window_start']} | "
            f"packets={int(row['packet_count'])} | "
            f"prediction={row['prediction']} | "
            f"P(DDOS)={row['ddos_probability']:.6f} | "
            f"P(NORMAL)={row['normal_probability']:.6f}"
        )

    print("\n[7] Output:")
    print(OUTPUT_FILE)

    print("\n" + "=" * 60)
    print("TASK #169 COMPLETE")
    print("=" * 60)


if __name__ == "__main__":
    main()
